class SelectDatasetPage(_StepPage):
    def __init__(self, state: dict, parent=None):
        super().__init__(1, "Select Dataset",
                         "Select the local dataset directory to assess.", parent)
        self._state = state
        row = QHBoxLayout()
        self._path_edit = QLineEdit()
        self._path_edit.setPlaceholderText("Path to dataset directory…")
        self._path_edit.textChanged.connect(lambda t: state.update({"dataset_path": t}))
        if state.get("dataset_path"):
            self._path_edit.setText(str(state["dataset_path"]))
        browse = QPushButton("Browse…")
        browse.clicked.connect(self._browse)
        row.addWidget(self._path_edit, 1)
        row.addWidget(browse)
        self.body.addLayout(row)
        self._status = QLabel("")
        self._status.setWordWrap(True)
        self.body.addWidget(self._status)
        note = QLabel(
            "The dataset directory will be assessed using the configured A1–A8 engines. "
            "Only local directories are accepted."
        )
        note.setWordWrap(True)
        note.setObjectName("mutedText")
        self.body.addWidget(note)

    def _browse(self):
        path = QFileDialog.getExistingDirectory(self, "Select dataset directory")
        if path:
            self._path_edit.setText(path)
            self._state["dataset_path"] = path

    def validate(self) -> bool:
        path = self._path_edit.text().strip()
        if not path:
            self._status.setText("Please select a dataset directory.")
            return False
        p = Path(path)
        if not p.is_dir():
            self._status.setText(f"Directory not found: {path}")
            return False
        self._status.setText("")
        self._state["dataset_path"] = path
        return True


