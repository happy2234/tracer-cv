class StepIndicator(QFrame):
    """Vertical list of numbered steps with active/done/pending states."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setFixedWidth(200)
        self.setObjectName("scopePanel")
        layout = QVBoxLayout(self)
        layout.setContentsMargins(10, 14, 10, 14)
        layout.setSpacing(4)
        header = QLabel("ASSESSMENT STEPS")
        header.setObjectName("metricLabel")
        layout.addWidget(header)
        self._step_frames: dict[int, QFrame] = {}
        for num, name, _ in STEPS:
            frame = QFrame()
            frame.setObjectName("stepCard")
            frame.setProperty("state", "pending")
            frame.setMinimumHeight(44)
            row = QHBoxLayout(frame)
            row.setContentsMargins(8, 6, 8, 6)
            num_label = QLabel(str(num))
            num_label.setFixedWidth(20)
            num_label.setAlignment(Qt.AlignCenter)
            num_label.setStyleSheet("font-weight:700; font-size:9pt;")
            name_label = QLabel(name)
            name_label.setWordWrap(True)
            row.addWidget(num_label)
            row.addWidget(name_label, 1)
            layout.addWidget(frame)
            self._step_frames[num] = frame
        layout.addStretch()

    def set_state(self, step: int, state: str) -> None:
        """state: 'pending' | 'active' | 'done'"""
        frame = self._step_frames.get(step)
        if frame:
            frame.setProperty("state", state)
            frame.style().unpolish(frame)
            frame.style().polish(frame)
            frame.update()


