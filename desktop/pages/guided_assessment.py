class RunAssessmentPage(_StepPage):
    assessment_completed = Signal(dict)  # emits assessment result

    def __init__(self, state: dict, services: dict, config: Any, parent=None):
        super().__init__(4, "Run Assessment", "Execute the assessment engines.", parent)
        self._state = state
        self._services = services
        self._config = config
        self._running = False

        self._start_button = QPushButton("Start Assessment")
        self._start_button.setObjectName("primary")
        self._start_button.clicked.connect(self._run)
        self.body.addWidget(self._start_button)

        self._progress = QProgressBar()
        self._progress.setRange(0, 0)  # indeterminate
        self._progress.setVisible(False)
        self.body.addWidget(self._progress)

        self._log = QTextEdit()
        self._log.setReadOnly(True)
        self._log.setMaximumHeight(180)
        self._log.setPlaceholderText("Assessment log will appear here…")
        self.body.addWidget(self._log)

        self._status_label = QLabel("")
        self._status_label.setWordWrap(True)
        self.body.addWidget(self._status_label)

    def _log_msg(self, msg: str) -> None:
        self._log.append(msg)

    def _run(self) -> None:
        if self._running:
            return
        dataset_path = self._state.get("dataset_path")
        if not dataset_path or not Path(dataset_path).is_dir():
            QMessageBox.warning(self, "Missing dataset",
                                "Please go back and select a valid dataset directory.")
            return

        manager = (self._services.get("assessment_manager")
                   if self._services else None)
        if manager is None:
            self._status_label.setText(
                "Assessment services are not available. "
                "Please restart the application and try again."
            )
            return

        self._running = True
        self._start_button.setEnabled(False)
        self._progress.setVisible(True)
        self._log_msg("Starting assessment…")

        name = self._state.get("name") or "Guided assessment"
        model_path = self._state.get("model_path")

        try:
            from backend.core.assessment import Assessment
            from pathlib import Path as _Path
            kwargs: dict[str, Any] = {
                "name": name,
                "dataset_path": str(dataset_path),
            }
            if model_path:
                kwargs["model_path"] = str(model_path)
            record = manager.create(**kwargs)
            self._log_msg(f"Assessment created: {record.get('assessment_id', '—')}")
            self._log_msg("Running engines…")
            result = manager.run(record["assessment_id"],
                                 on_event=lambda eng, msg, _: self._log_msg(f"[{eng}] {msg}"))
            self._state["assessment_result"] = result
            self._state["assessment_id"] = record.get("assessment_id", "")
            self._log_msg("Assessment completed.")
            self._status_label.setText(
                f"✓ Assessment {record.get('assessment_id', '')} completed."
            )
            self.assessment_completed.emit(result or {})
        except Exception as exc:
            self._log_msg(f"Error: {exc}")
            self._status_label.setText(f"Assessment failed: {exc}")
        finally:
            self._running = False
            self._progress.setVisible(False)
            self._start_button.setEnabled(True)

    def validate(self) -> bool:
        return bool(self._state.get("assessment_result") is not None
                    or self._state.get("assessment_id"))


class _SummaryStep(_StepPage):
    """Steps 5–8: summary card + navigate button."""

    def __init__(self, num: int, name: str, description: str,
                 nav_label: str, nav_key: str,
                 state: dict, parent=None):
        super().__init__(num, name, description, parent)
        self._state = state
        self._nav_key = nav_key
        self._summary_card = SectionCard(f"{name} Summary")
        self._summary_card.content.addWidget(QLabel("Load assessment results to see summary."))
        self.body.addWidget(self._summary_card)
        nav_button = QPushButton(f"Go to {nav_label}")
        nav_button.clicked.connect(lambda: self._navigate())
        self.body.addWidget(nav_button)
        self._nav_fn = None  # set by wizard

    def _navigate(self):
        if self._nav_fn:
            self._nav_fn(self._nav_key)

    def refresh(self, result: dict) -> None:
        """Update the summary card from assessment result."""
        while self._summary_card.content.count() > 1:
            item = self._summary_card.content.takeAt(1)
            if item.widget():
                item.widget().deleteLater()
        for key, label in self._summary_fields():
            value = result.get(key)
            if value is not None:
                lbl = QLabel(f"<b>{label}:</b>  {value}")
                lbl.setWordWrap(True)
                self._summary_card.content.addWidget(lbl)

    def _summary_fields(self) -> list[tuple[str, str]]:
        return []

    def validate(self) -> bool:
        return True


class ReviewFindingsPage(_SummaryStep):
    def __init__(self, state: dict, parent=None):
        super().__init__(5, "Review Findings",
                         "Review the findings generated by the assessment.",
                         "Findings Workspace", "FINDINGS", state, parent)

    def _summary_fields(self):
        return [("finding_count", "Findings"), ("highest_observed_severity", "Highest severity")]

    def refresh(self, result: dict) -> None:
        findings_block = result.get("findings_and_evidence", {})
        findings = findings_block.get("findings", []) if isinstance(findings_block, dict) else []
        counts: dict[str, int] = {}
        for f in findings if isinstance(findings, list) else []:
            sev = str(f.get("severity", "none")).lower()
            counts[sev] = counts.get(sev, 0) + 1
        while self._summary_card.content.count() > 1:
            item = self._summary_card.content.takeAt(1)
            if item.widget():
                item.widget().deleteLater()
        total = len(findings) if isinstance(findings, list) else 0
        self._summary_card.content.addWidget(QLabel(f"<b>Total findings:</b>  {total}"))
        for sev, count in sorted(counts.items()):
            badge = SeverityBadge(f"{sev.upper()}: {count}", sev)
            self._summary_card.content.addWidget(badge)
        if not findings:
            self._summary_card.content.addWidget(
                QLabel("No findings were recorded in the current assessment.")
            )


