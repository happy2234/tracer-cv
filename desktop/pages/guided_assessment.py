class GuidedAssessmentWizard(QWidget):
    """Nine-step guided assessment wizard.

    Emits navigate_to(str) for the main app to route to a workspace page.
    Does not duplicate engine logic; delegates execution to AssessmentManager.
    """
    navigate_to = Signal(str)

    def __init__(self, services: dict | None = None,
                 config: Any = None, parent=None):
        super().__init__(parent)
        self._services = services or {}
        self._config = config
        self._state: dict[str, Any] = {}
        self._current_step = 1
        self.step_count = len(STEPS)

        outer = QHBoxLayout(self)
        outer.setContentsMargins(0, 0, 0, 0)
        outer.setSpacing(0)

        self._indicator = StepIndicator()
        outer.addWidget(self._indicator)

        right = QVBoxLayout()
        right.setContentsMargins(24, 20, 24, 16)
        right.setSpacing(12)

        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QFrame.NoFrame)
        self._content_widget = QWidget()
        self._content_layout = QVBoxLayout(self._content_widget)
        self._content_layout.setContentsMargins(0, 0, 0, 0)
        scroll.setWidget(self._content_widget)
        right.addWidget(scroll, 1)

        # Navigation buttons
        btn_row = QHBoxLayout()
        self._back_button = QPushButton("← Back")
        self._back_button.clicked.connect(self._go_back)
        self._next_button = QPushButton("Next →")
        self._next_button.setObjectName("primary")
        self._next_button.clicked.connect(self._go_next)
        self._done_button = QPushButton("Done")
        self._done_button.setObjectName("success")
        self._done_button.setVisible(False)
        self._done_button.clicked.connect(lambda: self.navigate_to.emit("MISSION CONTROL"))
        btn_row.addWidget(self._back_button)
        btn_row.addStretch()
        btn_row.addWidget(self._done_button)
        btn_row.addWidget(self._next_button)
        right.addLayout(btn_row)

        outer.addLayout(right, 1)

        # Build step pages
        self._pages: dict[int, QWidget] = {}
        self._build_pages()
        self._show_step(1)

    def _build_pages(self) -> None:
        self._pages[1] = SelectDatasetPage(self._state)
        self._pages[2] = SelectModelPage(self._state)
        self._pages[3] = ConfigurePage(self._state, self._config)
        run_page = RunAssessmentPage(self._state, self._services, self._config)
        run_page.assessment_completed.connect(self._on_assessment_done)
        self._pages[4] = run_page
        self._pages[5] = ReviewFindingsPage(self._state)
        self._pages[6] = _SummaryStep(6, "Review Evidence", "Review the supporting evidence.",
                                       "Evidence Explorer", "EVIDENCE", self._state)
        self._pages[7] = _SummaryStep(7, "Verify Provenance", "Verify the provenance chain.",
                                       "Provenance Workspace", "Inference Provenance", self._state)
        self._pages[8] = _SummaryStep(8, "Review Audit", "Review the audit trail.",
                                       "Audit Trail", "AUDIT TRAIL", self._state)
        self._pages[9] = ReportPage(self._state)

        # Wire navigate_to signal through the summary pages
        for step in (6, 7, 8):
            page = self._pages[step]
            if hasattr(page, "_nav_fn"):
                page._nav_fn = lambda k: self.navigate_to.emit(k)
        if hasattr(self._pages[9], "_nav_fn"):
            self._pages[9]._nav_fn = lambda k: self.navigate_to.emit(k)
        if hasattr(self._pages[5], "_nav_fn"):
            self._pages[5]._nav_fn = lambda k: self.navigate_to.emit(k)

    def _on_assessment_done(self, result: dict) -> None:
        self._state["assessment_result"] = result
        # Refresh summary pages if they exist
        for step in (5,):
            page = self._pages.get(step)
            if page and hasattr(page, "refresh"):
                page.refresh(result.get("executive_summary") or result)
        # Auto-advance
        self._go_next()

    def _show_step(self, step: int) -> None:
        # Clear content
        while self._content_layout.count():
            item = self._content_layout.takeAt(0)
            if item.widget():
                item.widget().setParent(None)

        # Update indicator
        for s in range(1, self.step_count + 1):
            if s < step:
                self._indicator.set_state(s, "done")
            elif s == step:
                self._indicator.set_state(s, "active")
            else:
                self._indicator.set_state(s, "pending")

        page = self._pages.get(step)
        if page:
            self._content_layout.addWidget(page)
            page.show()

        self._current_step = step
        self._back_button.setEnabled(step > 1)
        is_last = (step == self.step_count)
        self._next_button.setVisible(not is_last)
        self._done_button.setVisible(is_last)

    def _go_next(self) -> None:
        page = self._pages.get(self._current_step)
        if page and hasattr(page, "validate") and not page.validate():
            return
        next_step = self._current_step + 1
        if next_step <= self.step_count:
            self._show_step(next_step)

    def _go_back(self) -> None:
        prev_step = self._current_step - 1
        if prev_step >= 1:
            self._show_step(prev_step)
